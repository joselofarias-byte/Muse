#!/usr/bin/env python3
"""Restore and validate the release keystore before a long Android build.

The script deliberately reads secrets from the environment instead of accepting
passwords as command-line arguments. It removes UTF-8 BOM/CRLF contamination,
validates the restored store and key entry with keytool, and writes the exact
keystore.properties consumed by app/build.gradle.kts.
"""

from __future__ import annotations

import argparse
import base64
import binascii
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

SECRET_NAMES = (
    "KEYSTORE_BASE64",
    "KEYSTORE_PASSWORD",
    "KEY_ALIAS",
    "KEY_PASSWORD",
)


def normalize_text(value: str, field: str) -> str:
    """Remove transport contamination without changing internal password text."""
    cleaned = value.replace("\ufeff", "").replace("ï»¿", "").strip()
    if not cleaned:
        raise ValueError(f"{field} is empty after BOM/whitespace cleanup")
    return cleaned


def decode_keystore(value: str) -> bytes:
    cleaned = value.replace("\ufeff", "").replace("ï»¿", "")
    cleaned = "".join(cleaned.split())
    try:
        return base64.b64decode(cleaned, validate=True)
    except (binascii.Error, ValueError) as error:
        raise ValueError("KEYSTORE_BASE64 is not valid base64") from error


def require_secrets() -> dict[str, str]:
    missing = [name for name in SECRET_NAMES if not os.environ.get(name)]
    if missing:
        raise ValueError("missing GitHub Actions secrets: " + ", ".join(missing))
    return {
        "store_password": normalize_text(os.environ["KEYSTORE_PASSWORD"], "KEYSTORE_PASSWORD"),
        "alias": normalize_text(os.environ["KEY_ALIAS"], "KEY_ALIAS"),
        "key_password": normalize_text(os.environ["KEY_PASSWORD"], "KEY_PASSWORD"),
        "keystore_base64": os.environ["KEYSTORE_BASE64"],
    }


def keytool_path() -> str:
    java_home = os.environ.get("JAVA_HOME")
    candidates = []
    if java_home:
        candidates.append(Path(java_home) / "bin" / "keytool")
        candidates.append(Path(java_home) / "bin" / "keytool.exe")
    found = shutil.which("keytool")
    if found:
        candidates.append(Path(found))
    for candidate in candidates:
        if candidate.is_file():
            return str(candidate)
    raise RuntimeError("keytool was not found; configure JDK before signing preflight")


def run_keytool(args: list[str], env: dict[str, str], stage: str) -> str:
    command = [
        keytool_path(),
        "-J-Duser.language=en",
        "-J-Duser.country=US",
        *args,
    ]
    result = subprocess.run(command, env=env, capture_output=True, text=True)
    if result.returncode != 0:
        # Keytool diagnostics can echo aliases, paths, or password-like input.
        raise RuntimeError(f"keystore preflight {stage} failed")
    return result.stdout


def write_private(path: Path, content: bytes) -> None:
    """Replace sensitive files atomically; never create a world-readable copy."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".signing-", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as output:
            os.fchmod(output.fileno(), 0o600)
            output.write(content)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def escape_property(value: str) -> str:
    """Encode a value for Java Properties.load(InputStream), not UTF-8."""
    escapes = {"\\": "\\\\", "\t": "\\t", "\n": "\\n", "\r": "\\r", "\f": "\\f"}
    result = []
    for char in value:
        if char in escapes:
            result.append(escapes[char])
        elif char in " =:#!":
            result.append("\\" + char)
        elif not 0x20 <= ord(char) <= 0x7E:
            encoded = char.encode("utf-16-be", errors="surrogatepass")
            result.extend(
                f"\\u{int.from_bytes(encoded[i:i + 2], 'big'):04x}"
                for i in range(0, len(encoded), 2)
            )
        else:
            result.append(char)
    return "".join(result)


def write_properties(path: Path, keystore_path: Path, values: dict[str, str]) -> None:
    properties = {
        "storeFile": str(keystore_path.resolve()),
        "storePassword": values["store_password"],
        "keyAlias": values["alias"],
        "keyPassword": values["key_password"],
    }
    content = "# Generated by ci/script/validate_release_signing.py\n"
    content += "".join(f"{key}={escape_property(value)}\n" for key, value in properties.items())
    write_private(path, content.encode("ascii"))


def validate_key(keystore: Path, values: dict[str, str], env: dict[str, str]) -> str:
    common = [
        "-keystore", str(keystore),
        "-storepass:env", "MUSE_STORE_PASSWORD",
        "-alias", values["alias"],
    ]
    fingerprint = run_keytool(["-list", "-v", *common], env, "store/alias")
    owner = next(
        (line.strip()[len("Owner:"):].strip() for line in fingerprint.splitlines()
         if line.strip().startswith("Owner:")),
        None,
    )
    if owner is None:
        raise RuntimeError("keystore preflight certificate subject unavailable")
    if re.search(r'(?:^|,\s*)CN\s*=\s*"?Android Debug"?\s*(?:,|$)', owner, re.IGNORECASE):
        raise ValueError("Android debug certificates cannot sign production releases")
    # Listing a store does not unlock its private key or check the key password.
    with tempfile.TemporaryDirectory(prefix="signing-check-") as directory:
        request = Path(directory) / "request.csr"
        write_private(request, b"")
        run_keytool(
            ["-certreq", *common, "-keypass:env", "MUSE_KEY_PASSWORD",
             "-file", str(request)],
            env,
            "private key/key password",
        )
    return fingerprint


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--keystore-out", type=Path, required=True)
    parser.add_argument("--properties-out", type=Path, required=True)
    args = parser.parse_args()
    try:
        values = require_secrets()
        keystore_bytes = decode_keystore(values["keystore_base64"])
        if len(keystore_bytes) < 32:
            raise ValueError("decoded keystore is unexpectedly small")
        write_private(args.keystore_out, keystore_bytes)
        digest = hashlib.sha256(keystore_bytes).hexdigest()

        tool_env = os.environ.copy()
        tool_env["MUSE_STORE_PASSWORD"] = values["store_password"]
        tool_env["MUSE_KEY_PASSWORD"] = values["key_password"]
        fingerprint = validate_key(args.keystore_out, values, tool_env)
        write_properties(args.properties_out, args.keystore_out, values)
        fingerprint_line = next(
            (match.group(0) for match in re.finditer(
                r"SHA-?256: (?:[0-9A-Fa-f]{2}:){31}[0-9A-Fa-f]{2}", fingerprint,
            )),
            "fingerprint unavailable",
        )
        print(f"release signing preflight PASS: bytes={len(keystore_bytes)} sha256={digest}")
        print(fingerprint_line)
        print(f"properties={args.properties_out.resolve()}")
        return 0
    except (OSError, RuntimeError, ValueError) as error:
        print(f"release signing preflight failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
